create_database(){
  validate_db_identifier "$DB_NAME" && validate_db_identifier "$DB_USER" || return 1
  systemctl start mariadb
  local pe="$(sql_escape "$DB_PASS")"
  mysql_root <<SQL
CREATE DATABASE IF NOT EXISTS \`${DB_NAME}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '${DB_USER}'@'localhost' IDENTIFIED BY '${pe}';
ALTER USER '${DB_USER}'@'localhost' IDENTIFIED BY '${pe}';
GRANT ALL PRIVILEGES ON \`${DB_NAME}\`.* TO '${DB_USER}'@'localhost';
FLUSH PRIVILEGES;
SQL
}
