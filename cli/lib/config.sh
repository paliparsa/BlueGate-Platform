#!/usr/bin/env bash
ask_value(){ local var prompt default secret current value; var="$1"; prompt="$2"; default="${3:-}"; secret="${4:-no}"; current="${!var:-}"; [[ -z "$current" && -n "$default" ]] && current="$default"; if [[ "$secret" == yes ]]; then if [[ -n "$current" ]]; then read -rsp "$prompt [saved, Enter=keep]: " value || true; echo; [[ -n "$value" ]] && printf -v "$var" '%s' "$value"; else read -rsp "$prompt: " value || true; echo; printf -v "$var" '%s' "$value"; fi; else read -rp "$prompt${current:+ [$current]}: " value || true; printf -v "$var" '%s' "${value:-$current}"; fi; }
ask_optional(){ local var prompt current value; var="$1"; prompt="$2"; current="${!var:-}"; read -rp "$prompt${current:+ [$current]} (Enter=keep, -=disable): " value || true; [[ "$value" == - ]] && value="" || value="${value:-$current}"; printf -v "$var" '%s' "$value"; }

configure_wizard(){
  require_root; try_extract_php_config; header
  echo "Configuration wizard — secrets are never passed as CLI arguments."; echo
  [[ -z "$DB_PASS" ]] && DB_PASS="$(rand_hex 16)"
  [[ -z "$WEBHOOK_SECRET" ]] && WEBHOOK_SECRET="$(rand_hex 20)"
  [[ -z "$TELEGRAM_WEBHOOK_SECRET" ]] && TELEGRAM_WEBHOOK_SECRET="$(rand_hex 20)"
  [[ -z "$SWAPWALLET_CALLBACK_SECRET" ]] && SWAPWALLET_CALLBACK_SECRET="$(rand_hex 20)"
  ask_value DOMAIN "Domain (without https)"
  ask_value BOT_TOKEN "Telegram bot token" "" yes
  ask_value BOT_USERNAME "Bot username without @"
  ask_value ADMIN_IDS "Admin Telegram IDs, comma separated"
  ask_value SUPPORT_USERNAME "Support username" "BlueGateSupport"
  ask_value REPO_URL "Git repository" "$DEFAULT_REPO_URL"
  ask_value APP_DIR "Install directory" "$DEFAULT_APP_DIR"
  ask_value DB_NAME "Database name" "bluegate_platform"
  ask_value DB_USER "Database user" "bluegate_user"
  ask_value DB_PASS "Database password" "" yes
  ask_value BRAND_NAME "Brand name" "BlueGate"
  ask_value THEME_COLOR "Theme color" "#1d9bf0"
  ask_optional FORCE_JOIN_CHANNEL "Force-join channel"
  ask_optional RESEND_API_KEY "Resend API key"
  ask_optional RESEND_FROM_EMAIL "Resend sender"
  ask_value ENABLE_SSL "Enable SSL? yes/no" "yes"
  [[ "${ENABLE_SSL,,}" =~ ^(yes|y)$ ]] && ask_optional SSL_EMAIL "Let's Encrypt email"
  ask_value BACKUP_KEEP "Release backups to keep" "5"
  ask_value DB_BACKUP_DAYS "DB backup retention days" "14"
  validate_domain "$DOMAIN" || { fail "Invalid domain"; return 1; }
  validate_db_identifier "$DB_NAME" || { fail "Invalid DB name"; return 1; }
  validate_db_identifier "$DB_USER" || { fail "Invalid DB user"; return 1; }
  [[ "$(admin_array_php)" != "[]" ]] || { fail "At least one numeric ADMIN_ID is required"; return 1; }
  save_env
  ok "Configuration saved to $ENV_FILE"
}

